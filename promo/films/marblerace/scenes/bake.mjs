// Bakes Race 1 (seed 38) into race1.js so node (cue sheets) and Chromium (pictures) play the very same race.
// The physics is chaotic, and Math.sin/cos can differ by an ulp between the node and Chromium engines, so running
// simulate() in both diverges after ~25 s. Run once after changing race.js or the race setup:  node bake.mjs
import { writeFileSync } from 'node:fs'
import { simulate } from './race.js'
import { SIGN_IDS } from '../../signs3kit.js'
const S = simulate({ seed: 38, ids: SIGN_IDS, drag: { taurus: 0.35, cancer: 0.36, pisces: 0.25 }, kick: { aries: 300 }, T: 75 })
const b64 = Buffer.from(S.frames.buffer).toString('base64')
writeFileSync(new URL('./race1.js', import.meta.url), `// generated by bake.mjs (seed 38): do not edit\nexport const RACE1 = ${JSON.stringify({ n: S.n, order: S.order, finishT: S.finishT, events: S.events })}\nexport const RACE1_FRAMES = '${b64}'\n`)
console.log('race1.js', (b64.length / 1e6).toFixed(2), 'MB · order', S.order.join(' '))
