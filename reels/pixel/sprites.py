# runtime

def _rgba(hexcol):
    h = hexcol.lstrip("#")
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255)


def _rows(name):
    if name not in SPRITES:
        raise KeyError(f"unknown sprite {name!r}; expected one of {NAMES}")
    return [r for r in SPRITES[name]["grid"].strip("\n").split("\n")]


def size(name):
    rows = _rows(name)
    return (max(len(r) for r in rows), len(rows))


def _blink(rows):
    """Close the eyes: each eye becomes a 1px line along its lowest row,
    and the pixels above it take the colour of the skin just above the eye."""
    g = [list(r) for r in rows]
    h = len(g)
    eye = {(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c in "ew"}
    for (x, y) in eye:
        if (x, y + 1) in eye:
            # find skin above this vertical run
            yy = y
            while (x, yy - 1) in eye:
                yy -= 1
            above = rows[yy - 1][x] if yy > 0 else "."
            if above in "ewO.":
                # fall back to a neighbour beside the eye
                for dx in (-1, 1, -2, 2):
                    c = rows[y][x + dx] if 0 <= x + dx < len(rows[y]) else "."
                    if c not in "ewO.":
                        above = c
                        break
            g[y][x] = above
        else:
            g[y][x] = "e"
    return ["".join(r) for r in g]


def _bob(rows, feet):
    """Shift everything above the feet down by 1px; feet stay planted."""
    w = max(len(r) for r in rows)
    rows = [r.ljust(w, ".") for r in rows]
    h = len(rows)
    split = h - feet
    out = [list(r) for r in rows]
    out[0] = ["."] * w
    for y in range(1, split + 1):
        src = rows[y - 1]
        if y < split:
            out[y] = list(src)
        else:
            out[y] = [s if s != "." else f for s, f in zip(src, rows[y])]
    return ["".join(r) for r in out]


def _render(rows, pal):
    w = max(len(r) for r in rows)
    img = Image.new("RGBA", (w, len(rows)), (0, 0, 0, 0))
    px = img.load()
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == ".":
                continue
            col = pal.get(c) or COMMON.get(c)
            if col is None:
                raise ValueError(f"no colour for {c!r}")
            px[x, y] = _rgba(col)
    return img


_cache = {}


def _variant(name, bob, blink):
    key = (name, bob, blink)
    if key not in _cache:
        spr = SPRITES[name]
        rows = _rows(name)
        if blink:
            rows = _blink(rows)
        if bob:
            rows = _bob(rows, spr["feet"])
        _cache[key] = _render(rows, spr["palette"])
    return _cache[key]


def frame(name, t):
    """RGBA sprite at native size for time t (seconds)."""
    bob = int(t * BOB_FPS) % 2
    idx = NAMES.index(name) if name in NAMES else 0
    offset = (idx * 1.37) % BLINK_EVERY       # desync blinks between sprites
    blink = ((t + offset) % BLINK_EVERY) < BLINK_LEN
    return _variant(name, bob, blink).copy()


def glyph(name):
    """Small zodiac symbol, single cream colour with a 1px darker shadow below."""
    rows = GLYPHS[name].strip("\n").split("\n")
    w = max(len(r) for r in rows)
    h = len(rows)
    img = Image.new("RGBA", (w, h + 1), (0, 0, 0, 0))
    px = img.load()
    fg, sh = _rgba(GLYPH_COLOUR), _rgba(GLYPH_SHADOW)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c != ".":
                px[x, y + 1] = sh
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c != ".":
                px[x, y] = fg
    return img
